using System;
using System.Diagnostics;
using System.Globalization;
using System.IO;
using System.Threading;
using System.Threading.Tasks;

namespace Temno.Media.Cache;

/// <summary>
/// Writes a single scaled JPEG thumbnail for a video frame via the external ffmpeg utility
/// (WP-20 frame-extract pipeline reused for still output).
/// </summary>
public sealed class FfmpegThumbnailGenerator
{
    /// <summary>Pure, testable ffmpeg argument string. The poster keeps the shown aspect with an even width.</summary>
    public static string BuildArguments(string mediaPath, double sourceSeconds, int height, string outputPath)
    {
        if (string.IsNullOrEmpty(mediaPath))
        {
            throw new ArgumentException("Path cannot be null or empty.", nameof(mediaPath));
        }

        if (string.IsNullOrEmpty(outputPath))
        {
            throw new ArgumentException("Output path cannot be null or empty.", nameof(outputPath));
        }

        if (height <= 0)
        {
            throw new ArgumentOutOfRangeException(nameof(height), "Height must be positive.");
        }

        // WP-420: no input seek for a poster at 0 s. Every still asks for 0, and an input seek, even to 0, left
        // FFmpeg with no frame of a JPEG, so no .jpg ever got a thumbnail. For video, a seek to 0 changes nothing.
        var seek = FfmpegPlaybackDecoder.ShouldEmitInputSeek(sourceSeconds, out var ss)
            ? $"-ss {ss} "
            : "";
        // -q:v 5 ~ Mac's JPEG quality 0.75; -f image2 keeps the muxer explicit for temp filenames.
        return $"-y {seek}-i \"{mediaPath}\" -vframes 1 -vf \"{PosterFilter(height)}\" -q:v 5 -f image2 \"{outputPath}\"";
    }

    /// <summary>
    /// WP-192. The JPEG poster drops alpha, so an alpha-only render (caption .mov, qtrle argb) came out
    /// black — reproduced on 26 of 27 files in the owner's caption-review project. The frame is now
    /// composited over a neutral checkerboard first, so transparent pixels read as transparency and an
    /// opaque source is unchanged (the overlay of an opaque frame is the frame). The checkerboard is
    /// generated by geq on a split of the scaled frame, so no second input and no fixed size are needed.
    /// </summary>
    public static string PosterFilter(int height)
    {
        const string cell = "if(eq(mod(floor(X/8)+floor(Y/8),2),0),88,60)";
        // WP-405: `dar` is the shown aspect, so a source with non-square pixels gets an unsqueezed poster
        // (scale=-2 kept the stored aspect); ffmpeg's autorotate has already turned a rotated source.
        return $"scale=trunc(dar*{height}/2)*2:{height},setsar=1,format=rgba,split[bg][fg];[bg]format=rgb24,{CheckerboardFilter(cell)}[bgc];[bgc][fg]overlay=format=auto";
    }

    private static string CheckerboardFilter(string cell) => $"geq=r='{cell}':g='{cell}':b='{cell}'";

    public async Task GenerateAsync(
        string mediaPath,
        double sourceSeconds,
        int height,
        string outputPath,
        CancellationToken cancellationToken = default)
    {
        if (!File.Exists(mediaPath))
        {
            throw new FileNotFoundException("Media file not found.", mediaPath);
        }

        var ffmpegPath = FFmpegResolver.GetFFmpegPath();
        var arguments = BuildArguments(mediaPath, sourceSeconds, height, outputPath);

        using var process = new Process();
        process.StartInfo.FileName = ffmpegPath;
        process.StartInfo.Arguments = arguments;
        process.StartInfo.UseShellExecute = false;
        process.StartInfo.RedirectStandardOutput = true;
        process.StartInfo.RedirectStandardError = true;
        process.StartInfo.CreateNoWindow = true;

        if (!process.Start())
        {
            throw new InvalidOperationException($"Failed to start ffmpeg process: '{ffmpegPath}'");
        }
        using var cancellationRegistration = ProcessCancellation.KillOnCancellation(process, cancellationToken);

        var stdoutTask = process.StandardOutput.ReadToEndAsync(cancellationToken);
        var stderrTask = process.StandardError.ReadToEndAsync(cancellationToken);

        await process.WaitForExitAsync(cancellationToken).ConfigureAwait(false);
        await stdoutTask.ConfigureAwait(false);
        var stderr = await stderrTask.ConfigureAwait(false);

        if (process.ExitCode != 0)
        {
            throw new InvalidOperationException($"ffmpeg exited with code {process.ExitCode}. Stderr: {stderr}");
        }
    }
}
